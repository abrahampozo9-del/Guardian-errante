// Simulación de la historia y alcanzabilidad: node test/run.js
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const page = await b.newPage();
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.goto('file://' + process.cwd() + '/' + (process.env.PAGE || 'guardian.html'));
  await page.waitForFunction(() => typeof G !== 'undefined' && G.worlds && G.worlds.exterior, null, { timeout: 30000 });
  await page.evaluate(() => { const l = document.getElementById('cargando'); if (l) l.remove(); });
  const res = await page.evaluate(() => {
    const log = []; let fails = 0;
    const check = (w, ok) => { log.push((ok ? 'OK   ' : 'FALLO ') + w); if (!ok) fails++; };
    const step = () => { G.just = new Set(G.queue); G.queue.clear(); G.update(1 / 60); };
    const skip = () => { let n = 0; while ((G.st === 'DIALOG' || G.st === 'CINE' || G.st === 'CHOICE' || G.st === 'LOAD') && n++ < 80) { if (G.st === 'CINE') G.endCine(); else if (G.st === 'CHOICE') { const c = G.choice; G.choice = null; G.st = 'PLAY'; c.cb(0); } else if (G.st === 'LOAD') { G.loading.t = 99; G.loading.built = false; G.updateLoad(0); } else { G.dlgChars = 9999; G.nextPage(); } } };
    const walk = (k, s) => { G.keys.add(k); for (let i = 0; i < s * 60; i++) { step(); skip(); } G.keys.delete(k); };
    const bfs = (w, sx, sy) => { const seen = new Uint8Array(w.w * w.h), q = [[sx, sy]]; seen[sy * w.w + sx] = 1; while (q.length) { const [x, y] = q.shift(); for (const [a, c] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) { const X = x + a, Y = y + c; if (X < 0 || Y < 0 || X >= w.w || Y >= w.h || seen[Y * w.w + X] || w.solid(X, Y)) continue; seen[Y * w.w + X] = 1; q.push([X, Y]); } } return seen; };
    const near = (w, r, x, y) => { for (let j = -1; j <= 1; j++) for (let i = -1; i <= 1; i++) { const X = x + i, Y = y + j; if (X >= 0 && Y >= 0 && X < w.w && Y < w.h && r[Y * w.w + X]) return true; } return false; };
    const ow = G.worlds.exterior;
    let r = bfs(ow, WG.doorX, WG.doorY + 1);
    const count = r.reduce((a, v) => a + v, 0);
    log.push('casillas alcanzables antes de La Linde: ' + count);
    check('alcanza hoguera', near(ow, r, WG.fireX, WG.fireY + 1));
    check('alcanza cruz', near(ow, r, WG.crossX, WG.crossY + 1));
    check('alcanza El Greco y la caseta', near(ow, r, WG.grecoX + 1, WG.grecoY + 1) && near(ow, r, WG.casetaX, WG.casetaY + 1));
    check('salida norte cerrada antes', !near(ow, r, WG.exitN[0], WG.exitN[1]));
    for (const k of ow.pickups) if (k.id && !['reliquia_higueras', 'reliquia_sierra'].includes(k.id)) check('alcanza ' + k.id, near(ow, r, Math.floor(k.x / 16), Math.floor(k.y / 16)));
    for (const [n, p] of Object.entries(WG.ruins || {})) if (p[1] > 66) check('alcanza ruina ' + n, near(ow, r, p[0], p[1]));
    if (WG.encina) check('alcanza la encina seca', near(ow, r, WG.encina[0], WG.encina[1] + 1));
    for (const L of ow.lairs) if (L.y > 67) check('guarida ' + L.name, near(ow, r, L.x, L.y) || L.kinds.includes(MK.AHOGADO));
    G.openBrambles();
    r = bfs(ow, WG.doorX, WG.doorY + 1);
    log.push('alcanzables después: ' + r.reduce((a, v) => a + v, 0));
    check('salida norte abierta', near(ow, r, WG.exitN[0], WG.exitN[1]));
    for (const k of ow.pickups) if (k.id) check('alcanza (abierto) ' + k.id, near(ow, r, Math.floor(k.x / 16), Math.floor(k.y / 16)));
    check('alcanza manantial', near(ow, r, WG.springX, WG.springY + 1));
    for (const [n, p] of Object.entries(WG.ruins || {})) check('alcanza (abierto) ruina ' + n, near(ow, r, p[0], p[1]));
    for (const L of ow.lairs) check('guarida (abierto) ' + L.name, near(ow, r, L.x, L.y) || L.kinds.includes(MK.AHOGADO));
    // secciones
    const pw = G.getWorld('pantano'), rp = bfs(pw, 50, 176);
    check('pantano: hotel', near(pw, rp, WS.hotelDoor[0], WS.hotelDoor[1] + 1));
    check('pantano: observatorio', near(pw, rp, WS.observatorio[0], WS.observatorio[1] + 1));
    check('pantano: salida a La Bolera', near(pw, rp, 54, 1) || near(pw, rp, 52, 2));
    const bw = G.getWorld('bolera'), rb = bfs(bw, 54, 126);
    check('bolera: El Hornico', near(bw, rb, 27, 71));
    check('bolera: cascada', near(bw, rb, 6, 47) || near(bw, rb, 6, 48));
    check('bolera: agujas', near(bw, rb, WS.agujas[0], WS.agujas[1] + 1));
    check('bolera: presa', near(bw, rb, WS.bossX, WS.bossY));
    check('bolera: cueva PB4', near(bw, rb, WS.pb4[0], WS.pb4[1] + 1));
    delete G.worlds.pantano; delete G.worlds.bolera;
    // historia
    const talk = key => { const n = G.world.npcs.find(n => n.key === key); if (!n) return false; G.player.x = n.x; G.player.y = n.y + 16; G.player.dir = 1; G.interact(); skip(); return true; };
    const use = id => { const pr = G.world.props.find(p => p.id === id); if (!pr) return false; G.player.x = pr.x; G.player.y = pr.y + 14; G.player.dir = 1; G.interact(); skip(); return true; };
    G.newGame(); skip();
    check('empieza sin espada', !G.player.hasSword && G.stage === 0);
    G.player.x = 16.5 * 16; G.player.y = 5 * 16 + 4; G.player.dir = 1; G.interact(); skip();
    check('coge la espada', G.player.hasSword && G.stage === 1);
    G.player.x = 23 * 16 + 8; G.player.y = 2 * 16 + 8; walk('ArrowRight', 1.5);
    check('baja a planta baja', G.world.id === 'casa_baja');
    G.player.x = 9 * 16 + 8; G.player.y = 11 * 16 + 4; walk('ArrowDown', 1.0);
    check('sale al exterior', G.world.outdoor); skip();
    for (let i = 0; i < 10; i++) step();
    check('6 engendros de la ribera', G.stage === 2 && G.world.monsters.filter(m => m.quest).length === 6);
    for (const m of [...G.world.monsters]) if (m.quest && !m.dead) G.damageMonster(m, 999, false, 0, 1);
    skip(); check('ribera limpia', G.stage === 3);
    use('radio'); check('radio', G.stage === 4);
    G.world.monsters = []; talk('cura'); check('Padre Tomás', G.stage === ETAPA.GRECO);
    talk('santiago'); check('Santiago', G.stage === ETAPA.CASETA);
    use('caseta'); check('caseta', G.stage === ETAPA.CRUZ);
    G.world.monsters = []; use('cruz'); check('cae Miguel', G.stage === ETAPA.MIGUEL && !!G.miguelDemon);
    G.player.invul = 999; G.damageMonster(G.miguelDemon, 60, false, 0, 1, true); for (let i = 0; i < 5; i++) { step(); skip(); }
    talk('miguel'); check('Miguel abre La Linde', G.stage === ETAPA.HOTEL && G.worlds.exterior.get(WG.brambles[0][0], WG.brambles[0][1]) !== T.BRAMBLE);
    G.player.x = WG.exitN[0] * 16 + 8; G.player.y = 1 * 16 + 8; step(); skip();
    check('viaja al pantano', G.world.id === 'pantano');
    talk('gerente'); const od = G.world.monsters.find(m => m.obs); G.damageMonster(od, 99999, false, 0, 1, true); skip();
    check('la esfera', G.stage === ETAPA.HORNICO);
    G.player.x = 54 * 16 + 8; G.player.y = 1 * 16 + 8; step(); skip();
    check('viaja a La Bolera', G.world.id === 'bolera');
    talk('monitora'); use('cascada'); use('agujas'); check('las agujas', G.stage === ETAPA.BESTIA);
    G.player.x = WS.bossX * 16; G.player.y = (WS.bossY + 4) * 16; for (let i = 0; i < 5; i++) step(); skip();
    check('aparece la Bestia', !!G.boss);
    G.damageMonster(G.boss, 99999, false, 0, -1); skip();
    talk('anticristo'); check('tentación', G.stage === ETAPA.SIERRA);
    G.save(); check('carga partida', G.load() && G.stage === ETAPA.SIERRA);
    // rendimiento
    G.enter('exterior', 80 * 16, 120 * 16, 0); G.day = 0.7;
    const t0 = performance.now(); for (let i = 0; i < 120; i++) G.render(document.createElement('canvas').getContext('2d'), 800, 450, 1);
    log.push('render: ' + ((performance.now() - t0) / 120).toFixed(1) + ' ms/fotograma');
    log.push(fails ? 'FALLOS ' + fails : 'SIMULACION OK');
    return log;
  });
  console.log(res.join('\n')); if (errs.length) console.log('ERRORES', errs);
  await b.close();
})();
